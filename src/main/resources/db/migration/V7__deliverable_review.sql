-- V7：稿件版本与送审（补审核人与审核时间）
--
-- 【为什么稿件要按"版本"存，而不是每单一个文件路径】
-- 设计这行的工作量几乎全在改稿上。一单改三版是常态，如果只留最后一个文件：
--   1) 客户说"还是第一版好"，文件已经没了，只能重画；
--   2) 结算时说不清"这单为什么做了两周"，因为没有改稿次数的证据；
--   3) 设计师被质疑"效率低"时，拿不出"是客户改了五版"的凭据。
-- 按版本号存，上面三件事全部有据可查。uk_order_version 保证同一单版本号不重复，
-- 并发上传时由数据库兜底（第二个请求会撞唯一键，转成业务错误而不是产生两个 V3）。
--
-- 【为什么审核结果存 1/2/3 而不是布尔值】
-- "待审"是一个真实且会停留很久的状态：稿子发过去了，客户还没回话。
-- 用布尔值（通过/未通过）表达不了这个中间态，最后只能拿"未通过"冒充，
-- 于是看板上全是"被退回"，主管没法判断到底卡在客户那边还是卡在设计师这边。
--
-- 【为什么退回要单独落 rework_log，而不是只改 deliverable 的状态】
-- deliverable 记的是"这一版的结果"，rework_log 记的是"发生了返工"这件事件。
-- 前者会随着改稿被反复覆盖（V2 退回、V3 通过，V2 那条再没人看），
-- 后者是只增不改的事实流水，返工率只能从它算 —— 这是评价设计师和判断客户难缠程度的硬指标。
--
-- 【会出什么问题】
-- 文件存在本地磁盘，数据库只存相对路径。换机器/重装容器时文件会丢，
-- 而数据库记录还在 —— 点下载报 404，看起来像系统坏了。
-- 怎么解决：upload-dir 配在项目外的固定目录并纳入备份；
-- 下载接口对"文件不存在"给出明确文案（"文件已丢失，请联系管理员"），不抛 500。
-- =====================================================================

-- ---------- 1. 稿件：审核留痕 ----------
ALTER TABLE deliverable
    ADD COLUMN reviewed_by BIGINT NULL COMMENT '审核人（录入客户反馈的人）' AFTER uploaded_by,
    ADD COLUMN reviewed_at DATETIME NULL COMMENT '审核时间' AFTER reviewed_by,
    -- 按单查版本、按结果筛"还没通过的稿"都用得上
    ADD KEY idx_order_review (order_id, review_result);

-- ---------- 2. 返工记录：补返工责任人 ----------
-- 返工通常是"原稿的设计师自己改"，但也会出现"换人接手"。
-- 不记这一列，统计就只能按原稿人算，换人的情况会把账算到已经不管这单的人头上。
ALTER TABLE rework_log
    ADD COLUMN rework_by BIGINT NULL COMMENT '实际返工的人（换人接手时与原稿人不同）' AFTER reason;
