-- V4：一个员工最多一个登录账号
--
-- 为什么必须由数据库来保证：
-- 开号逻辑里有"先查有没有账号，没有才插入"这一步。两个人同时点"开账号"，
-- 两次查询都会返回"没有"，于是插出两条账号 —— 表现是这个人有两个登录名，
-- 而系统只认识其中一个（登录后按 employee_id 反查业绩，两条账号查同一份数据，
-- 却各自有不同的密码和角色）。这种脏数据在界面上看不出来，只有对账或
-- 员工反馈"我登进去看到的是别人的数据"时才会暴露。
--
-- 代码层的校验只能防"手滑"，防不了并发；唯一索引才是真正的防线。
-- 之所以现在才加：V1 建表时还没有开号功能，那时加约束属于过度设计；
-- 有了开号接口，就必须有对应的约束。
-- =============================================================================

-- 先删掉普通索引，再建唯一索引：MySQL 加唯一索引会自己建索引，
-- 两者同时存在等于同一列上有两份索引，写入白白多一次维护成本。
ALTER TABLE sys_user DROP INDEX idx_employee;

-- employee_id 允许为 NULL（纯系统账号），
-- MySQL 的唯一索引允许多个 NULL，不会把这类账号互相冲突。
ALTER TABLE sys_user ADD UNIQUE KEY uk_employee (employee_id);
