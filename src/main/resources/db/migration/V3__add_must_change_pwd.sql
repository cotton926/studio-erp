-- =============================================================================
-- V3：账号表增加「强制修改密码」标记
--
-- 【为什么必须单独一列，不能靠"密码等于初始密码"来判断】
-- 判断"是否初始密码"需要拿明文比对，而库里只有 BCrypt 哈希，理论上做得到但
-- 每登录一次就要跑一次 BCrypt 校验（60ms），而且管理员重置成同一个密码时
-- 无法区分"刚重置"和"用户自己又改回来了"。
--
-- 【为什么不用 updated_at = created_at 这种推断】
-- 改个手机号、启停账号都会动 updated_at，推断结果不可靠。
--
-- 【业务流程】
-- · AdminBootstrapRunner 建管理员、管理员重置他人密码 → 置 1
-- · 用户自己改密码成功 → 置 0
-- · 前端拿到 mustChangePwd=1 时，除了改密码接口，其他页面一律拦在改密弹窗里
--   （服务端也要拦：见 AuthInterceptor 中的强制改密判断，不能只靠前端）
-- =============================================================================

ALTER TABLE sys_user
    ADD COLUMN must_change_pwd TINYINT NOT NULL DEFAULT 0
        COMMENT '1=必须修改密码（首次登录/管理员重置后）'
        AFTER status;
