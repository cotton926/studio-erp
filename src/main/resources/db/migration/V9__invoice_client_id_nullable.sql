-- V9：开放 invoice.client_id 为可空
--
-- 【为什么现在才改】
-- V5 已经把 payment.client_id 放开了，但漏了 invoice —— 开票表在 v2 之前一直没人用
-- （没有开票功能），所以这个约束一直没暴露。本次上线开票后，第一张发票插入就报
-- "Field 'client_id' doesn't have a default value"。
--
-- 【为什么是"可空"而不是"建客户档案"】
-- 订单本身就是手填客户名的（见 V5 的说明）。开票只依赖订单上的客户名与抬头，
-- 强迫每张票必须先建客户档案，会让开票按钮变成"要先去做三件别的事"的按钮，
-- 最后没人用。等真的需要"按客户统计开票/回款"时再补客户域，届时回填。
-- =============================================================================
ALTER TABLE invoice
    MODIFY COLUMN client_id BIGINT NULL COMMENT '客户ID；客户域本期不做，此列为空';
